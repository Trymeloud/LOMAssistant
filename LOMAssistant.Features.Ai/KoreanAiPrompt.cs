    internal static int HintIndex(string text)
    {
        int a = (text ?? "").IndexOf(HintMarker, StringComparison.Ordinal);
        int b = (text ?? "").IndexOf(LegacyHintMarker, StringComparison.Ordinal);
        return a < 0 ? b : b < 0 ? a : Math.Min(a, b);
    }
    internal static int HintLength(string text, int index) => text.Substring(index).StartsWith(LegacyHintMarker, StringComparison.Ordinal)
        ? LegacyHintMarker.Length : HintMarker.Length;
    // Old sessions remain readable, including their shorter legacy marker.
    internal static string NormalizeHints(string text, string replacement) => (text ?? "")
        .Replace(LegacyHintMarker, replacement).Replace(HintMarker, replacement);

