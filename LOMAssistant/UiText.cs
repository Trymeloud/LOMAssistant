/// 先整句查；查不到再查带 {0} 的句式（拼进去的数字、按键、名字原样保留）；
/// 带颜色等标签的、用「 · 」「　」或换行拼起来的，拆开一段段查。查不到的照原样显示中文。
/// 表里的译文欢迎懂韩语、日语的玩家指正。
